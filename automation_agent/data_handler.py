    @staticmethod
    def save_payment_info(payment_url: str, screenshot_path: str, data: Dict) -> None:
        """Save payment information to JSON file."""
        import datetime
        
        payment_data = {
            "payment_url": payment_url,
            "screenshot": screenshot_path,
            "timestamp": datetime.datetime.now().isoformat(),
            "applicant_name": f"{data.get('first_name', '')} {data.get('last_name', '')}".strip(),
            "email": data.get('email', '')
        }
        
        with open("payment_link.json", 'w', encoding='utf-8') as f:
            json.dump(payment_data, f, indent=4, ensure_ascii=False)
        
        print("[+] Payment link saved to: payment_link.json")
