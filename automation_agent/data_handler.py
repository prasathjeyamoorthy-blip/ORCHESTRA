"""Data loading and validation module."""

import json
import os
from typing import Optional, Dict
from config import DEFAULT_COUNTRY_CODE, DEFAULT_STATE_CODE, DEFAULT_ISD_CODE, DEFAULT_ISD_LABEL


class DataLoadError(Exception):
    """Raised when application data cannot be loaded or parsed."""
    pass


class DataHandler:
    """Handles loading and validation of application data from JSON."""
    
    @staticmethod
    def load_from_json(json_file: str = "data.json") -> Optional[Dict]:
        """Load application data from JSON file.

        Inputs are assumed to be pre-validated, so no per-field requirement
        checks are performed here. Only structural problems (missing file,
        malformed JSON, unreadable file) raise a DataLoadError.
        """
        if not os.path.exists(json_file):
            print(f"[ERROR] JSON file not found: {json_file}")
            DataHandler._create_sample_json(json_file)
            return None
        
        try:
            with open(json_file, 'r', encoding='utf-8') as f:
                data = json.load(f)
        except json.JSONDecodeError as e:
            raise DataLoadError(f"Invalid JSON format in {json_file}: {e}") from e
        except OSError as e:
            raise DataLoadError(f"Could not read {json_file}: {e}") from e

        if not isinstance(data, dict):
            raise DataLoadError(f"{json_file} must contain a JSON object, got {type(data).__name__}")

        # Add internal fields
        data["country_code"] = DEFAULT_COUNTRY_CODE
        data["state_code"] = DEFAULT_STATE_CODE
        data["isd_code"] = DEFAULT_ISD_CODE
        data["isd_label"] = DEFAULT_ISD_LABEL

        print(f"[+] Loaded data from {json_file}")
        return data
    
